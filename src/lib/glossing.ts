/**
 * Перевод фразы в ЖЕСТОВЫЙ порядок — «основной смысл» вместо слова в слово.
 *
 * ЗАЧЕМ. Пословный показ глухие не понимают, и это не придирка: в жестовом
 * языке своя грамматика. Предлогов и связок в нём нет вовсе, порядок слов
 * другой, вопросительное слово идёт в конце. Хуже того, в пословном режиме
 * каждый предлог, которого нет в библиотеке, показывается ДАКТИЛЕМ — по
 * буквам. То есть между смысловыми знаками вклинивается «в-в-в», «н-а» — шум,
 * из-за которого фраза и рассыпается.
 *
 * ЧТО ЭТОТ МОДУЛЬ ДЕЛАЕТ. Выбрасывает служебные слова, выносит время вперёд,
 * вопросительное слово в конец, отрицание — после сказуемого.
 *
 * ЧЕГО НЕ ДЕЛАЕТ, СОЗНАТЕЛЬНО. Не переставляет глагол в конец фразы и не
 * пересказывает смысл своими словами. Для первого нужен разбор по частям речи,
 * для второго — языковая модель; вслепую двигать глагол опаснее, чем оставить
 * как есть: перепутанный порядок меняет смысл, а лишнее слово — только мешает.
 *
 * ГЛАВНОЕ. Списки ниже — первое приближение, а не истина. Их надо править
 * вместе с сурдопереводчиком: он скажет, какие слова в КЖЯ показывают, а какие
 * нет. Поэтому всё лежит плоскими таблицами, а не размазано по коду.
 */

/**
 * Служебные слова, которым в жестовом языке не соответствует отдельный знак.
 * Предлоги и связки передаются положением рук и мимикой, союзы — паузой.
 */
const FUNCTION_WORDS = new Set([
  // предлоги
  'в', 'во', 'на', 'с', 'со', 'из', 'изо', 'к', 'ко', 'по', 'у', 'о', 'об', 'обо',
  'для', 'за', 'над', 'под', 'подо', 'при', 'про', 'до', 'от', 'ото', 'без',
  'через', 'сквозь', 'около', 'возле', 'вокруг', 'между', 'среди', 'кроме',
  'вместо', 'ради', 'насчёт', 'насчет',
  // связка «быть» в настоящем времени: «я студент», а не «я есть студент».
  //
  // «есть» здесь СОЗНАТЕЛЬНО нет, хотя формально это связка: гораздо чаще это
  // глагол «кушать». На «я не хочу есть» выброс превращал фразу в «Я ХОЧУ НЕ»
  // — смысл наизнанку. Правило простое: слово, у которого есть смысловое
  // значение, из списка убираем, даже если иногда оно служебное.
  'являюсь', 'является', 'являются',
  // частицы
  'же', 'ли', 'бы', 'б', 'вот', 'ведь', 'уж', 'ну', 'разве', 'неужели', 'лишь',
  // союзы, которые в жестовом языке заменяет пауза
  'и', 'а', 'что', 'чтобы', 'чтоб', 'ибо',
]);

/**
 * Время в жестовом языке идёт ПЕРЕД сообщением: «вчера я в магазин ходил» ->
 * ВЧЕРА Я МАГАЗИН ХОДИТЬ. Так слушающий сразу знает, о каком времени речь.
 *
 * Выносим вперёд только то время, что стоит в НАЧАЛЕ фразы (см. TIME_HOIST_
 * WINDOW). Иначе «работал и потом пошёл домой» превращается в «ПОТОМ работал
 * пошёл»: слово из второй части уезжает в начало и ломает последовательность
 * событий. Время в середине относится к своему куску фразы и остаётся там.
 */
const TIME_WORDS = new Set([
  'вчера', 'сегодня', 'завтра', 'позавчера', 'послезавтра',
  'сейчас', 'потом', 'раньше', 'позже', 'давно',
  'утром', 'днём', 'днем', 'вечером', 'ночью',
]);

/** До какой позиции слово времени считается относящимся ко всей фразе. */
const TIME_HOIST_WINDOW = 3;

/** Вопросительное слово в жестовом языке ставится в КОНЕЦ фразы. */
const QUESTION_WORDS = new Set([
  'кто', 'что', 'где', 'куда', 'откуда', 'когда', 'почему', 'зачем',
  'сколько', 'какой', 'какая', 'какое', 'какие', 'чей', 'чья', 'чьё', 'чье',
]);

/** Отрицание идёт ПОСЛЕ сказуемого: «я не хочу» -> Я ХОЧУ НЕ. */
const NEGATIONS = new Set(['не', 'нет', 'ни']);

export interface GlossResult {
  /** Что показывать аватару, по порядку. */
  tokens: string[];
  /** Что выброшено — показываем пользователю, чтобы правка была видна. */
  dropped: string[];
  /** Была ли фраза вопросом (по знаку «?»). */
  question: boolean;
}

/** Токенизация — та же, что в пословном режиме, чтобы поиск жестов совпадал. */
function tokenize(text: string): string[] {
  return text
    .toLowerCase()
    .replace(/[^а-яёa-z\s-]/g, ' ')
    .split(/\s+/)
    .filter(Boolean);
}

/**
 * Фраза -> последовательность знаков в жестовом порядке.
 *
 * Принимает СЫРОЙ текст, а не токены: знак «?» нужен до того, как пунктуация
 * будет срезана — от него зависит, вопрос это или нет, а значит и судьба слова
 * «что» (союз выбрасываем, вопросительное — оставляем и уносим в конец).
 */
export function toGloss(text: string): GlossResult {
  const question = /\?/.test(text);
  const tokens = tokenize(text);

  const dropped: string[] = [];
  const time: string[] = [];
  const tail: string[] = [];      // вопросительные слова — в конец
  const body: string[] = [];

  tokens.forEach((tok, i) => {
    if (question && QUESTION_WORDS.has(tok)) {
      tail.push(tok);
      return;
    }
    if (FUNCTION_WORDS.has(tok)) {
      dropped.push(tok);
      return;
    }
    if (TIME_WORDS.has(tok) && i < TIME_HOIST_WINDOW) {
      time.push(tok);
      return;
    }
    body.push(tok);
  });

  // Отрицание — после слова, к которому относится.
  for (let i = 0; i < body.length - 1; i++) {
    if (NEGATIONS.has(body[i]) && !NEGATIONS.has(body[i + 1])) {
      [body[i], body[i + 1]] = [body[i + 1], body[i]];
      i++;   // уже переставили, соседа не трогаем
    }
  }

  const out = [...time, ...body, ...tail];

  // Подряд идущие повторы («да да да») показывать дважды смысла нет.
  const deduped = out.filter((tok, i) => i === 0 || tok !== out[i - 1]);

  return { tokens: deduped, dropped, question };
}

/** Как показать глоссу человеку: ВЧЕРА Я МАГАЗИН ХОДИТЬ. */
export function glossToText(tokens: string[]): string {
  return tokens.join(' ').toUpperCase();
}
